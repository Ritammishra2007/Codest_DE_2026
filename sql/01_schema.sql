-- =====================================================================
-- YouTube Video Sharing Database: Phase 2 Schema
-- Deliverable: sql/01_schema.sql (Checkpoint 1)
--
-- Rules:
-- 1. All tables reside in schema "youtube".
-- 2. Contains ONLY: PK, FK, UNIQUE, NOT NULL, and CHECK constraints.
-- 3. NO extra tuning indexes (only default PK/UNIQUE b-tree indexes).
-- 4. Satisfies all rows of seed_data without errors.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS youtube;
SET search_path TO youtube;

-- Clean up any existing tables (in reverse dependency order)
DROP TABLE IF EXISTS ad_impressions CASCADE;
DROP TABLE IF EXISTS playlist_items CASCADE;
DROP TABLE IF EXISTS playlists CASCADE;
DROP TABLE IF EXISTS comments CASCADE;
DROP TABLE IF EXISTS video_reactions CASCADE;
DROP TABLE IF EXISTS watch_events CASCADE;
DROP TABLE IF EXISTS subscriptions CASCADE;
DROP TABLE IF EXISTS videos CASCADE;
DROP TABLE IF EXISTS channels CASCADE;
DROP TABLE IF EXISTS users CASCADE;


-- PART 1: CORE USER & CONTENT TABLES 
-- 1. USERS
-- Registered users on YouTube India.
CREATE TABLE users (
    user_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    display_name   VARCHAR(100) NOT NULL,
    country_code   CHAR(2)      NOT NULL,
    birth_year     INT          NULL,
    premium_until  DATE         NULL,
    created_at     TIMESTAMPTZ  NOT NULL,

    -- Constraints
    CONSTRAINT chk_users_country_code CHECK (char_length(country_code) = 2),
    CONSTRAINT chk_users_birth_year   CHECK (birth_year IS NULL OR (birth_year >= 1900 AND birth_year <= 2026))
);

-- 2. CHANNELS
-- Creator channels owned by registered users.
CREATE TABLE channels (
    channel_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id       INT          NOT NULL,
    handle              VARCHAR(60)  NOT NULL UNIQUE,
    channel_name        VARCHAR(150) NOT NULL,
    country_code        CHAR(2)      NOT NULL,
    is_verified         BOOLEAN      NOT NULL DEFAULT FALSE,
    monetization_status VARCHAR(20)  NOT NULL,
    subscriber_count    INT          NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ  NOT NULL,

    -- Foreign Key
    CONSTRAINT fk_channels_owner FOREIGN KEY (owner_user_id) 
        REFERENCES users (user_id) ON DELETE CASCADE,

    -- Constraints
    CONSTRAINT chk_channels_handle       CHECK (handle LIKE '@%'),
    CONSTRAINT chk_channels_country_code CHECK (char_length(country_code) = 2),
    CONSTRAINT chk_channels_monetization CHECK (monetization_status IN ('ELIGIBLE', 'NOT_ELIGIBLE', 'SUSPENDED')),
    CONSTRAINT chk_channels_sub_count    CHECK (subscriber_count >= 0)
);

-- 3. VIDEOS
-- Video catalog (regular videos and Shorts).
CREATE TABLE videos (
    video_id         CHAR(11)     PRIMARY KEY,
    channel_id       INT          NOT NULL,
    title            VARCHAR(255) NOT NULL,
    description      TEXT         NULL,
    category         VARCHAR(30)  NOT NULL,
    duration_sec     INT          NOT NULL,
    is_short         BOOLEAN      NOT NULL,
    is_made_for_kids BOOLEAN      NOT NULL DEFAULT FALSE,
    visibility       VARCHAR(20)  NOT NULL,
    uploaded_at      TIMESTAMPTZ  NOT NULL,
    published_at     TIMESTAMPTZ  NULL,
    view_count       INT          NOT NULL DEFAULT 0,

    -- Foreign Key
    CONSTRAINT fk_videos_channel FOREIGN KEY (channel_id) 
        REFERENCES channels (channel_id) ON DELETE CASCADE,

    -- Constraints
    CONSTRAINT chk_videos_id_len    CHECK (char_length(video_id) = 11),
    CONSTRAINT chk_videos_duration  CHECK (duration_sec > 0),
    CONSTRAINT chk_videos_view_cnt  CHECK (view_count >= 0),
    CONSTRAINT chk_videos_category  CHECK (category IN ('Comedy', 'Cooking', 'Education', 'Film', 'Gaming', 'Music', 'News', 'Sports', 'Tech', 'Vlogs')),
    CONSTRAINT chk_videos_visibility CHECK (visibility IN ('PRIVATE', 'PUBLIC', 'SCHEDULED', 'UNLISTED')),
    -- Shorts are 60 seconds or less; long videos are strictly > 60 seconds
    CONSTRAINT chk_videos_shorts_duration CHECK (
        (is_short = TRUE  AND duration_sec <= 60) OR 
        (is_short = FALSE AND duration_sec > 60)
    ),
    -- Private videos have no published_at timestamp; all other visibilities must have one
    CONSTRAINT chk_videos_private_published CHECK (
        (visibility = 'PRIVATE' AND published_at IS NULL) OR 
        (visibility <> 'PRIVATE' AND published_at IS NOT NULL)
    )
);

-- 4. PLAYLISTS
-- Collections of videos curated by users.
CREATE TABLE playlists (
    playlist_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id INT          NOT NULL,
    title         VARCHAR(150) NOT NULL,
    visibility    VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,

    -- Foreign Key
    CONSTRAINT fk_playlists_owner FOREIGN KEY (owner_user_id) 
        REFERENCES users (user_id) ON DELETE CASCADE,

    -- Constraints
    CONSTRAINT chk_playlists_visibility CHECK (visibility IN ('PRIVATE', 'PUBLIC', 'UNLISTED'))
);

-- 5. SUBSCRIPTIONS
-- M:N relationship linking users to channels they subscribe to.
CREATE TABLE subscriptions (
    user_id       INT         NOT NULL,
    channel_id    INT         NOT NULL,
    notifications VARCHAR(20) NOT NULL,
    subscribed_at TIMESTAMPTZ NOT NULL,

    -- Composite Primary Key
    PRIMARY KEY (user_id, channel_id),

    -- Foreign Keys
    CONSTRAINT fk_subscriptions_user    FOREIGN KEY (user_id) 
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_subscriptions_channel FOREIGN KEY (channel_id) 
        REFERENCES channels (channel_id) ON DELETE CASCADE,

    -- Constraints
    CONSTRAINT chk_subscriptions_notifications CHECK (notifications IN ('ALL', 'NONE', 'PERSONALIZED'))
);


-- PART 2: ENGAGEMENT & MONETIZATION TABLES 
-- 6. WATCH_EVENTS
-- Logs every video view (authenticated users or guest sessions).
CREATE TABLE watch_events (
    watch_id       BIGINT      PRIMARY KEY,
    user_id        INT         NULL,
    video_id       CHAR(11)    NOT NULL,
    started_at     TIMESTAMPTZ NOT NULL,
    watch_seconds  INT         NOT NULL,
    device         VARCHAR(20) NOT NULL,
    traffic_source VARCHAR(20) NOT NULL,

    -- Foreign Keys
    -- If user deletes account, preserve watch event for analytics by setting user_id to NULL
    CONSTRAINT fk_watch_user  FOREIGN KEY (user_id) 
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_watch_video FOREIGN KEY (video_id) 
        REFERENCES videos (video_id) ON DELETE CASCADE,

    -- Constraints
    CONSTRAINT chk_watch_seconds CHECK (watch_seconds >= 0),
    CONSTRAINT chk_watch_device  CHECK (device IN ('ANDROID', 'IOS', 'TV', 'WEB')),
    CONSTRAINT chk_watch_traffic CHECK (traffic_source IN ('EXTERNAL', 'HOME', 'SEARCH', 'SHORTS_FEED', 'SUBSCRIPTION', 'SUGGESTED'))
);

-- 7. VIDEO_REACTIONS
-- Likes and dislikes by signed-in users on videos.
CREATE TABLE video_reactions (
    user_id    INT         NOT NULL,
    video_id   CHAR(11)    NOT NULL,
    reaction   VARCHAR(10) NOT NULL,
    reacted_at TIMESTAMPTZ NOT NULL,

    -- Composite Primary Key (a user can have at most one reaction per video)
    PRIMARY KEY (user_id, video_id),

    -- Foreign Keys
    CONSTRAINT fk_reactions_user  FOREIGN KEY (user_id) 
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_reactions_video FOREIGN KEY (video_id) 
        REFERENCES videos (video_id) ON DELETE CASCADE,

    -- Constraints
    CONSTRAINT chk_reactions_type CHECK (reaction IN ('LIKE', 'DISLIKE'))
);

-- 8. COMMENTS
-- User comments on videos, including threaded replies.
CREATE TABLE comments (
    comment_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id          CHAR(11)    NOT NULL,
    user_id           INT         NOT NULL,
    parent_comment_id INT         NULL,
    body              TEXT        NOT NULL,
    like_count        INT         NOT NULL DEFAULT 0,
    is_pinned         BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ NOT NULL,

    -- Foreign Keys
    CONSTRAINT fk_comments_video  FOREIGN KEY (video_id) 
        REFERENCES videos (video_id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_user   FOREIGN KEY (user_id) 
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_parent FOREIGN KEY (parent_comment_id) 
        REFERENCES comments (comment_id) ON DELETE CASCADE,

    -- Constraints
    CONSTRAINT chk_comments_like_cnt    CHECK (like_count >= 0),
    -- Replies (parent_comment_id IS NOT NULL) can never be pinned
    CONSTRAINT chk_comments_pinned_reply CHECK (is_pinned = FALSE OR parent_comment_id IS NULL)
);

-- 9. PLAYLIST_ITEMS
-- Videos contained within a playlist, ordered by position.
CREATE TABLE playlist_items (
    playlist_id INT         NOT NULL,
    position    INT         NOT NULL,
    video_id    CHAR(11)    NOT NULL,
    added_at    TIMESTAMPTZ NOT NULL,

    -- Composite Primary Key (position is unique within a playlist)
    PRIMARY KEY (playlist_id, position),

    -- Foreign Keys
    CONSTRAINT fk_playlist_items_playlist FOREIGN KEY (playlist_id) 
        REFERENCES playlists (playlist_id) ON DELETE CASCADE,
    CONSTRAINT fk_playlist_items_video    FOREIGN KEY (video_id) 
        REFERENCES videos (video_id) ON DELETE CASCADE,

    -- Constraints
    CONSTRAINT chk_playlist_items_pos CHECK (position >= 1),
    -- A video cannot appear more than once in the same playlist
    CONSTRAINT uq_playlist_video UNIQUE (playlist_id, video_id)
);

-- 10. AD_IMPRESSIONS
-- Advertisements shown during video playback and the earned revenue.
CREATE TABLE ad_impressions (
    impression_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    watch_id      BIGINT        NOT NULL,
    ad_format     VARCHAR(20)   NOT NULL,
    revenue_inr   NUMERIC(8, 4) NOT NULL,
    shown_at      TIMESTAMPTZ   NOT NULL,

    -- Foreign Key
    CONSTRAINT fk_ad_watch FOREIGN KEY (watch_id) 
        REFERENCES watch_events (watch_id) ON DELETE CASCADE,

    -- Constraints
    CONSTRAINT chk_ad_format  CHECK (ad_format IN ('MIDROLL', 'PREROLL')),
    CONSTRAINT chk_ad_revenue CHECK (revenue_inr >= 0.0000)
);